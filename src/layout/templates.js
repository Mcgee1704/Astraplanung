export function newItemId() {
  return (
    globalThis.crypto?.randomUUID?.() ??
    'teil-' +
      Date.now().toString(36) +
      '-' +
      Math.random().toString(36).slice(2)
  );
}

export function makeItem(kind, overrides = {}) {
  const definition = catalog[kind] || catalog.custom;
  const { group, ...properties } = definition;
  return {
    id: newItemId(),
    kind,
    x: 0,
    y: 0,
    z: 0,
    rotation: 0,
    ...properties,
    ...overrides,
  };
}

export function makeLayout(variant = '1a', vehicle = {}) {
  if (variant === 'empty') return [];
  if (typeof variant === 'string' && variant.startsWith('tour-'))
    return makeSourceItems(variant, vehicle, makeItem);
  if (!['1a', '2a', '10'].includes(variant)) return [];
  const length = Math.max(1, Number(vehicle.length) || 4200);
  const width = Math.max(1, Number(vehicle.width) || 1900);
  const height = Math.max(1, Number(vehicle.height) || 2100);
  const mm = Math.round;
  // Scale free-standing furniture to the measured room. Purchased devices retain their example envelopes.
  const furnished = (kind, name, x0, y0, x1, y1, options = {}) =>
    makeItem(kind, {
      name,
      x: mm(x0 * length),
      y: mm(y0 * width),
      length: Math.max(1, mm(x1 * length) - mm(x0 * length)),
      width: Math.max(1, mm(y1 * width) - mm(y0 * width)),
      ...options,
    });
  const device = (kind, x, y, options = {}) =>
    makeItem(kind, { x: mm(length * x), y: mm(width * y), ...options });
  const roof = device('solar', 0.42, 0.2, { z: height });
  if (variant === '2a')
    return [
      furnished('bed', 'Längsbett', 0.55, 0, 1, 0.6, { z: 760 }),
      furnished('bath', 'Bad neben Bett', 0.73, 0.635, 1, 1),
      furnished('bench', 'Sitzbank', 0.04, 0, 0.3, 0.27),
      furnished('table', 'Tisch', 0.088, 0.28, 0.29, 0.46),
      furnished('kitchen', 'Küchenblock', 0.19, 0.7, 0.53, 1),
      furnished('cabinet', 'Stauraum', 0.35, 0, 0.51, 0.25),
      device('fresh', 0.76, 0.04),
      device('grey', 0.575, 0.04),
      device('battery', 0.62, 0.35),
      device('heater', 0.78, 0.39),
      device('pump', 0.91, 0.34),
      device('inverter', 0.605, 0.275, { z: 490 }),
      roof,
      makeItem('door', {
        x: mm(length * 0.012),
        y: Math.max(0, width - 30),
        length: mm(length * 0.155),
      }),
    ];
  const longBench = variant === '10';
  const bedLength = longBench
    ? Math.min(1500, mm(length * 0.42))
    : mm(length * 0.332);
  const bedStart = length - bedLength;
  const bathroom = furnished(
    'bath',
    'Bad am Eingang',
    0,
    0.6,
    longBench ? 0.225 : 0.21,
    1,
  );
  const hatch = makeItem('hatch', {
    name: 'Serviceklappe Heckbett',
    x: bedStart + 15,
    length: 790,
    height: 440,
  });
  return [
    makeItem('bed', {
      name: 'Heckbett',
      x: bedStart,
      length: bedLength,
      width,
      z: 760,
    }),
    bathroom,
    furnished('kitchen', 'Küchenblock', 0, 0, longBench ? 0.33 : 0.31, 0.3),
    furnished(
      'bench',
      longBench ? 'Sitzbank vor Bett' : 'Sitzbank',
      0.305,
      0.73,
      bedStart / length - 0.02,
      1,
    ),
    furnished(
      'table',
      'Esstisch',
      0.355,
      0.45,
      Math.min(0.565, bedStart / length - 0.035),
      0.69,
    ),
    furnished(
      'cabinet',
      'Schrank',
      longBench ? 0.35 : 0.335,
      0,
      longBench ? 0.48 : 0.52,
      0.255,
    ),
    makeItem('fresh', {
      x: bedStart + 35,
      y: mm(width * 0.07),
      serviceWidth: hatch.length,
      serviceHeight: hatch.height,
      serviceId: hatch.id,
    }),
    makeItem('grey', { x: bedStart + 35, y: mm(width * 0.66) }),
    makeItem('battery', { x: length - 380, y: mm(width * 0.41) }),
    makeItem('heater', { x: length - 450, y: mm(width * 0.21) }),
    makeItem('inverter', { x: length - 430, y: mm(width * 0.43), z: 480 }),
    makeItem('pump', { x: bedStart + 715, y: 70 }),
    roof,
    hatch,
    makeItem('door', {
      x: mm(length * 0.022),
      y: Math.max(0, width - 30),
      length: mm(length * 0.16),
      passageId: bathroom.id,
    }),
  ];
}
